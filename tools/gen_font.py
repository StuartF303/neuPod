#!/usr/bin/env python3
"""Generate the embedded bitmap fonts (app/gfx/fonts/*.c).

  font8x8.c  <- tools/data/font8x8_basic.h (Daniel Hepper's font8x8, PUBLIC DOMAIN; itself from
                the public-domain IBM VGA fonts).
  font16.c   <- DejaVu Sans rendered 1-bit by Pillow at --px pixels (Bitstream Vera licence,
                permissive; the notice is reproduced in app/gfx/fonts/README.md and in the
                generated file header).

Glyph storage: ASCII 32..126, `height` rows per glyph, one uint16_t per row, bit 15 = leftmost
pixel. Needs Pillow (for font16 only). Usage:
  python3 tools/gen_font.py [--ttf PATH] [--px N]
"""
import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "app", "gfx", "fonts")
FIRST, LAST = 32, 126


def emit_rows(rows, per_line=8):
    lines = []
    for i in range(0, len(rows), per_line):
        lines.append("    " + ", ".join("0x%04X" % r for r in rows[i:i + per_line]) + ",")
    return "\n".join(lines)


def gen_8x8():
    text = open(os.path.join(ROOT, "tools", "data", "font8x8_basic.h")).read()
    body = text[text.index("font8x8_basic[128][8]"):]
    glyphs = re.findall(r"\{\s*((?:0x[0-9A-Fa-f]{2}\s*,?\s*){8})\}", body)
    assert len(glyphs) == 128, len(glyphs)
    rows = []
    for ch in range(FIRST, LAST + 1):
        for b in re.findall(r"0x([0-9A-Fa-f]{2})", glyphs[ch]):
            v = int(b, 16)  # source: bit 0 = leftmost pixel
            out = 0
            for x in range(8):
                if v >> x & 1:
                    out |= 1 << (15 - x)
            rows.append(out)
    src = """// SPDX-License-Identifier: MPL-2.0
// GENERATED by tools/gen_font.py -- do not edit by hand.
// 8x8 fixed font, ASCII 32..126. Glyph data: font8x8_basic by Daniel Hepper
// (https://github.com/dhepper/font8x8), PUBLIC DOMAIN, derived from the public-domain IBM VGA
// fonts (Marcel Sondaar). See app/gfx/fonts/README.md.
#include "gfx_font.h"

static const uint16_t k_rows[] = {
%s
};

const gfx_font_t gfx_font_8x8 = {
    .height = 8,
    .ascent = 7,
    .first = %d,
    .last = %d,
    .fixed_w = 8,
    .widths = NULL,
    .rows = k_rows,
};
""" % (emit_rows(rows), FIRST, LAST)
    open(os.path.join(OUT, "font8x8.c"), "w").write(src)
    print("font8x8.c: %d rows" % len(rows))


def gen_16(ttf, px):
    from PIL import Image, ImageDraw, ImageFont
    font = ImageFont.truetype(ttf, px)
    ascent, descent = font.getmetrics()
    height = ascent + descent
    rows, widths = [], []
    for ch in range(FIRST, LAST + 1):
        adv = int(round(font.getlength(chr(ch))))
        im = Image.new("1", (24, height), 0)
        d = ImageDraw.Draw(im)
        d.fontmode = "1"
        d.text((0, 0), chr(ch), font=font, fill=1)
        bbox = im.getbbox()
        if bbox and bbox[2] > 16:
            sys.exit("glyph %r wider than 16 px (%d)" % (chr(ch), bbox[2]))
        adv = max(adv, 1)
        widths.append(adv)
        for y in range(height):
            v = 0
            for x in range(16):
                if im.getpixel((x, y)):
                    v |= 1 << (15 - x)
            rows.append(v)
    wtxt = ", ".join(str(w) for w in widths)
    src = """// SPDX-License-Identifier: MPL-2.0
// GENERATED by tools/gen_font.py -- do not edit by hand.
// Proportional %dpx-class font (cell height %d), ASCII 32..126, rendered 1-bit from DejaVu Sans.
//
// DejaVu Sans is derived from Bitstream Vera. Font licence (summarised; full text in
// app/gfx/fonts/README.md): Copyright (c) 2003 by Bitstream, Inc. All Rights Reserved. Bitstream
// Vera is a trademark of Bitstream, Inc. DejaVu changes are in the public domain. The Font
// Software may be embedded, used, copied and modified freely provided the above copyright notice
// and this permission notice are kept; it may not be sold by itself, and modified versions must
// not use the "Bitstream" or "Vera" names (this derived bitmap font is named "neuPod 16").
#include "gfx_font.h"

static const uint8_t k_widths[] = {
    %s
};

static const uint16_t k_rows[] = {
%s
};

const gfx_font_t gfx_font_16 = {
    .height = %d,
    .ascent = %d,
    .first = %d,
    .last = %d,
    .fixed_w = 0,
    .widths = k_widths,
    .rows = k_rows,
};
""" % (px, height, wtxt, emit_rows(rows), height, ascent, FIRST, LAST)
    open(os.path.join(OUT, "font16.c"), "w").write(src)
    print("font16.c: height %d ascent %d" % (height, ascent))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--ttf", default="/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf")
    ap.add_argument("--px", type=int, default=12)
    a = ap.parse_args()
    os.makedirs(OUT, exist_ok=True)
    gen_8x8()
    gen_16(a.ttf, a.px)


if __name__ == "__main__":
    main()
