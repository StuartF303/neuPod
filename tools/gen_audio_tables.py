"""Generates app/audio/audio_tables.inc: the full-scale sine table and the Q30 volume gain table."""
import math, sys
out = []
out.append("// SPDX-License-Identifier: MPL-2.0\n// GENERATED by tools/gen_audio_tables.py -- do not edit.\n")
out.append("// 1024-point sine, full scale (peak 0x7FFFFFFF), one cycle.\n#define SINE_TABLE_LEN 1024u\n"
           "static const int32_t k_sine[SINE_TABLE_LEN] = {\n")
vals = [int(round(0x7FFFFFFF * math.sin(2 * math.pi * i / 1024))) for i in range(1024)]
for i in range(0, 1024, 8):
    out.append("    " + ", ".join(str(v) for v in vals[i:i + 8]) + ",\n")
out.append("};\n\n// Q30 gain for an attenuation of n dB (n = 0..79); 80 dB and above is silence.\n"
           "static const uint32_t k_gain_q30[80] = {\n")
g = [int(round((1 << 30) * 10 ** (-n / 20))) for n in range(80)]
for i in range(0, 80, 8):
    out.append("    " + ", ".join(str(v) for v in g[i:i + 8]) + ",\n")
out.append("};\n")
open(sys.argv[1], "w").write("".join(out))
