#!/usr/bin/env python3
"""Convert a PNG to a C array of RGB565 pixels (Pillow only).

Writes OUT.c (const uint16_t NAME[W*H], row-major) and OUT.h (extern + NAME_WIDTH/NAME_HEIGHT).

BYTE ORDER -- read this:
  The neuPod ST7789 driver (platforms/rp2350/hal/hal_display.c) runs SPI1 in 16-bit frame mode,
  which shifts the HIGH byte of each uint16_t out first, which is what the ST7789 wants. So pixel
  arrays in this repo are NATIVE uint16_t RGB565 (value = r5<<11 | g6<<5 | b5) and the default
  here is NO byte swap. Use these directly with hal_display_blit() / gfx_image().

  --swap byte-swaps every pixel (0xF800 -> 0x00F8). That is what you need when the array is
  pushed as raw bytes over an 8-bit SPI/DMA path on a little-endian MCU (high byte must be the
  first byte in memory). Do NOT use --swap for arrays consumed by this repo's driver: red would
  become garbage colours.

Options:
  --downscale2   2x box downscale (average of each 2x2 block) before conversion
  --width/--height  expected output size (after downscale); error on mismatch
  --name         C identifier (default: derived from the output file name)
"""
import argparse
import os
import re
import sys

from PIL import Image


def box_downscale2(im):
    w, h = im.size
    src = im.load()
    out = Image.new("RGB", (w // 2, h // 2))
    dst = out.load()
    for y in range(h // 2):
        for x in range(w // 2):
            p = (src[2 * x, 2 * y], src[2 * x + 1, 2 * y], src[2 * x, 2 * y + 1],
                 src[2 * x + 1, 2 * y + 1])
            dst[x, y] = tuple((sum(q[i] for q in p) + 2) // 4 for i in range(3))
    return out


def rgb565(r, g, b):
    # Round to nearest (HAL_RGB565 truncates; rounding looks better for photos).
    r5 = (r * 31 + 127) // 255
    g6 = (g * 63 + 127) // 255
    b5 = (b * 31 + 127) // 255
    return (r5 << 11) | (g6 << 5) | b5


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("png")
    ap.add_argument("-o", "--out", required=True, help="output .c path (.h written alongside)")
    ap.add_argument("--name", help="C identifier for the array")
    ap.add_argument("--swap", action="store_true", help="byte-swap pixels (see BYTE ORDER above)")
    ap.add_argument("--downscale2", action="store_true", help="2x box downscale first")
    ap.add_argument("--width", type=int, help="expected width after downscale")
    ap.add_argument("--height", type=int, help="expected height after downscale")
    a = ap.parse_args()

    base = os.path.splitext(a.out)[0]
    name = a.name or re.sub(r"\W", "_", os.path.basename(base))
    im = Image.open(a.png).convert("RGB")
    if a.downscale2:
        im = box_downscale2(im)
    w, h = im.size
    if (a.width and a.width != w) or (a.height and a.height != h):
        sys.exit("size mismatch: got %dx%d, expected %sx%s" % (w, h, a.width, a.height))

    px = im.load()
    vals = []
    for y in range(h):
        for x in range(w):
            v = rgb565(*px[x, y])
            if a.swap:
                v = ((v & 0xFF) << 8) | (v >> 8)
            vals.append(v)

    cmd = "tools/png2rgb565.py " + os.path.basename(a.png) + (" --swap" if a.swap else "") + \
          (" --downscale2" if a.downscale2 else "")
    guard = "NEUPOD_" + name.upper() + "_H"
    hdr = os.path.basename(base) + ".h"
    with open(base + ".h", "w") as f:
        f.write("// SPDX-License-Identifier: MPL-2.0\n// GENERATED by %s -- do not edit.\n" % cmd)
        f.write("#ifndef %s\n#define %s\n\n#include <stdint.h>\n\n" % (guard, guard))
        f.write("#define %s_WIDTH %d\n#define %s_HEIGHT %d\n\n" % (name.upper(), w, name.upper(), h))
        f.write("/* %s RGB565, row-major, %dx%d. */\n" % (
            "BYTE-SWAPPED" if a.swap else "Native-endian", w, h))
        f.write("extern const uint16_t %s[%d];\n\n#endif\n" % (name, w * h))
    with open(base + ".c", "w") as f:
        f.write("// SPDX-License-Identifier: MPL-2.0\n// GENERATED by %s -- do not edit.\n" % cmd)
        f.write('#include "%s"\n\nconst uint16_t %s[%d] = {\n' % (hdr, name, w * h))
        for i in range(0, len(vals), 16):
            f.write("    " + ",".join("0x%04X" % v for v in vals[i:i + 16]) + ",\n")
        f.write("};\n")
    print("wrote %s.c/.h: %s %dx%d%s" % (base, name, w, h, " (byte-swapped)" if a.swap else ""))


if __name__ == "__main__":
    main()
