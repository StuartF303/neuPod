#
# Regenerates mobile/test/domain/library/collate_golden.tsv: the firmware's
# lib_collate_key() (app/library/lib_collate.c, compiled for the host) applied
# to a fixed set of names, so the app's Dart port can be checked byte for byte
# (owner decision 11). Run it whenever lib_collate.c changes, then run the
# app's tests.
#
# Usage: scripts/app/gen-collate-golden.sh
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"
OUT="$REPO/mobile/test/domain/library/collate_golden.tsv"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

cc -std=c11 -O1 -I"$REPO/app/include" -I"$REPO/app/third_party/fatfs" \
  -o "$TMP/collate_golden" "$HERE/collate_golden.c" "$REPO/app/library/lib_collate.c"

python3 - "$TMP/inputs.tsv" <<'PY'
import sys

names = [
    # tests/test_library.c
    "abba", "ABBA", "The Beatles", "Beatles", "THE BEATLES", "beatles", "The Band",
    "Theatre of Tragedy", "Them", "Theory", "Therapy", "The ", "A", "A Perfect Circle",
    "Perfect Circle", "An Horse", "horse", "Abba", "Anvil", "A ", "An ", "An",
    "Émile", "Emile", "Beyoncé", "Beyonce", "ß", "ss", "Æon", "Aeon",
    "Sigur Rós", "Sigur Ros", "Ørsted", "Orsted", "Dvořák", "Dvorak",
    "Łódź", "Lodz", "Œuvre", "Oeuvre", "Ĳ", "ij", "É", "F",
    "Zoé", "Zoe", "10cc", "99 Luftballons", "!!!", " leading space", "a", "ab c",
    "abc", "&", "~", "α", "0", "β", "あ", "\U0001f3b5", "Weird Al",
    "Yankovic, Weird Al", "Zed", "Yardbirds", "Zzz", "x", "The Y", "y", "The Zombies",
    # articles and near misses
    "the the", "The  Double", "THE", "the", "Thee", "a b", "an apple", "AN APPLE", "Ana",
    "A-ha", "Ané", "À la carte", "The\tTab", "The Nbsp",
    # symbols, digits, controls, DEL
    "#1 Hits", "(What's the Story)", "...And Justice", "_under", "`tick", "{brace}",
    "1999", "2Pac", "½ half", "× times", "÷ divide", "a\u007fb", "a\u0001b",
    "tab\there", "line\nbreak",
    # other scripts
    "Би-2", "Καλη", "日本", "가나",
    "العربية", "שלום", "ẞ",
    "ƀ", "Ǆ", "ɏ", "\U0001f600 smile", "\U00010348",
    # long names, cut at 96 bytes
    "a" * 200, "ß" * 60, "日" * 40, "The " + "z" * 120,
]
# Every code point of Latin-1 and Latin Extended-A/B, alone and inside a word.
for cp in list(range(0x20, 0x7f)) + list(range(0xa0, 0x250)):
    names.append(chr(cp))
    names.append("x" + chr(cp) + "y")

pairs = [(n, None) for n in names]
pairs += [("Weird Al", "Yankovic, Weird Al"), ("Weird Al", ""), ("Abba", "Zzz"),
          ("x", "The Y"), ("The Who", "Who, The"), ("Björk", "Bjork"),
          ("Anything", "An Sort"), ("A", "Æ")]

with open(sys.argv[1], "w") as f:
    for name, sort in pairs:
        n = name.encode("utf-8").hex()
        s = "-" if sort is None else sort.encode("utf-8").hex()
        f.write(f"{n}\t{s}\n")
PY

{
  echo "# Generated by scripts/app/gen-collate-golden.sh from app/library/lib_collate.c; do not edit."
  echo "# name (UTF-8 hex)	sort tag (UTF-8 hex, - for none)	lib_collate_key() (hex, cap 96)"
  "$TMP/collate_golden" <"$TMP/inputs.tsv"
} >"$OUT"
echo "wrote $(grep -vc '^#' "$OUT") cases to $OUT"
